import { type NewAppSubtype, type RepodogConfig } from '@repodog/cli-utils';
import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { runCommandOrThrow } from './runCommandOrThrow.ts';

const cliPath = fileURLToPath(new URL('../../../core/bin/repodog.mjs', import.meta.url));
const questionNames = ['name', 'description', 'owner', 'counterpartRepository'];

const getBootstrapSources = (): RepodogConfig['appBootstraps'] => ({
  dotnet: {
    ref: process.env.CLI_E2E_DOTNET_REF ?? 'main',
    repository: process.env.CLI_E2E_DOTNET_REPOSITORY ?? 'badbatch/repodog-dotnet-kickstarter',
  },
  nextjs: {
    ref: process.env.CLI_E2E_NEXTJS_REF ?? 'main',
    repository: process.env.CLI_E2E_NEXTJS_REPOSITORY ?? 'badbatch/repodog-nextjs-kickstarter',
  },
});

export const generateAppOrThrow = async (
  workspace: string,
  subtype: NewAppSubtype,
  name: string,
  counterpartRepository = '',
): Promise<string> => {
  const config: Partial<RepodogConfig> = {
    appBootstraps: getBootstrapSources(),
    language: 'typescript',
    packageManager: 'pnpm',
    questionOverrides: { new: { app: { [subtype]: { remove: questionNames } } } },
    templateVariables: {
      new: {
        app: {
          [subtype]: {
            counterpartRepository,
            description: 'An application generated by the Repodog CLI E2E suite.',
            name,
            namespace: 'GeneratedApi',
            owner: 'repodog-e2e',
          },
        },
      },
    },
  };

  // Supply answers through supported configuration, exercising the real CLI without terminal prompts.
  await writeFile(resolve(workspace, '.repodogrc'), JSON.stringify(config, undefined, 2));
  await runCommandOrThrow(workspace, process.execPath, [cliPath, 'new', 'app', subtype, '--verbose']);
  return resolve(workspace, name);
};
